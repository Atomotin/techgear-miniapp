  function invertMap(map) {
    const result = {};

    Object.keys(map).forEach(function (key) {
      const value = map[key];

      if (typeof value === "string" && value) {
        result[value] = key;
      }
    });

    return result;
  }
  const KZ_TO_RU = invertMap(RU_TO_KZ);

  function normalize(value) {
    return String(value || "").replace(/\s+/g, " ").trim();
  }

  function safeStorageGet(key) {
    try {
      return root && root.localStorage ? root.localStorage.getItem(key) : null;
    } catch (error) {
      return null;
    }
  }

  function safeStorageSet(key, value) {
    try {
      if (root && root.localStorage) {
        root.localStorage.setItem(key, value);
      }
    } catch (error) {}
  }

  function getLocale() {
    const stored = normalize(safeStorageGet(LOCALE_KEY));
    return stored === "kz" ? "kz" : DEFAULT_LOCALE;
  }

  function setLocale(locale) {
    const normalized = normalize(locale) === "kz" ? "kz" : DEFAULT_LOCALE;
    safeStorageSet(LOCALE_KEY, normalized);
    return normalized;
  }

  function toggleLocale(locale) {
    return normalize(locale) === "kz" ? "ru" : "kz";
  }

  function getDocumentLang(locale) {
    return normalize(locale) === "kz" ? "kk" : "ru";
  }

  function translateText(value, locale) {
    const source = normalize(value);

    if (!source) {
      return value;
    }

    if (normalize(locale) === "kz") {
      return Object.prototype.hasOwnProperty.call(RU_TO_KZ, source)
        ? RU_TO_KZ[source]
        : value;
    }

    if (normalize(locale) === "ru") {
      return Object.prototype.hasOwnProperty.call(KZ_TO_RU, source)
        ? KZ_TO_RU[source]
        : value;
    }

    return value;
  }

  function localizeValue(value, locale) {
    if (typeof value === "string") {
      return translateText(value, locale);
    }

    if (Array.isArray(value)) {
      return value.map(function (item) {
        return localizeValue(item, locale);
      });
    }

    if (value && typeof value === "object") {
      const result = {};
      const activeLocale = normalize(locale);

      Object.keys(value).forEach(function (key) {
        if (/(?:Ru|Kz)$/i.test(key)) {
          return;
        }

        if (activeLocale === "kz") {
          const shadowKey = key + "Kz";

          if (Object.prototype.hasOwnProperty.call(value, shadowKey)) {
            const shadowValue = value[shadowKey];
            const hasShadowValue =
              typeof shadowValue === "string" ? shadowValue.trim() : shadowValue !== null && shadowValue !== undefined;

            if (hasShadowValue) {
              result[key] = shadowValue;
              return;
            }
          }
        }

        if (activeLocale === "ru") {
          const shadowKey = key + "Ru";

          if (Object.prototype.hasOwnProperty.call(value, shadowKey)) {
            const shadowValue = value[shadowKey];
            const hasShadowValue =
              typeof shadowValue === "string" ? shadowValue.trim() : shadowValue !== null && shadowValue !== undefined;

            if (hasShadowValue) {
              result[key] = shadowValue;
              return;
            }
          }
        }

        result[key] = localizeValue(value[key], locale);
      });

      return result;
    }

    return value;
  }

  function preserveWhitespace(source, target) {
    const raw = String(source || "");
    const leading = raw.match(/^\s*/);
    const trailing = raw.match(/\s*$/);
    return (leading ? leading[0] : "") + target + (trailing ? trailing[0] : "");
  }

  function localizeAttributes(rootNode, locale) {
    const scope = rootNode && rootNode.querySelectorAll ? rootNode : document;
    const elements = scope.querySelectorAll
      ? scope.querySelectorAll("[placeholder], [aria-label], [title], [alt]")
      : [];

    Array.prototype.forEach.call(elements, function (element) {
      ["placeholder", "aria-label", "title", "alt"].forEach(function (attribute) {
        if (!element.hasAttribute(attribute)) {
          return;
        }

        const current = element.getAttribute(attribute);
        const translated = translateText(current, locale);

        if (translated !== current) {
          element.setAttribute(attribute, translated);
        }
      });
    });
  }

  function localizeDom(rootNode, locale) {
    const scope = rootNode || (root && root.document ? root.document.body : null);

    if (!scope || !root || !root.document) {
      return;
    }

    const walker = root.document.createTreeWalker(scope, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        const text = node && typeof node.nodeValue === "string" ? node.nodeValue : "";
        const parent = node && node.parentElement ? node.parentElement : null;

        if (!text.trim() || !parent) {
          return NodeFilter.FILTER_SKIP;
        }

        if (parent.closest("script, style, noscript, svg, code, pre")) {
          return NodeFilter.FILTER_SKIP;
        }

        return NodeFilter.FILTER_ACCEPT;
      },
    });

    const nodes = [];
    while (walker.nextNode()) {
      nodes.push(walker.currentNode);
    }

    nodes.forEach(function (node) {
      const current = node.nodeValue;
      const translated = translateText(current, locale);

      if (translated !== current) {
        node.nodeValue = preserveWhitespace(current, translated);
      }
    });

    localizeAttributes(scope, locale);
  }

  function applyLocale(locale) {
    if (!root || !root.document || !root.document.documentElement) {
      return;
    }

    const normalized = normalize(locale) === "kz" ? "kz" : DEFAULT_LOCALE;

    root.document.documentElement.lang = getDocumentLang(normalized);
    if (root.document.body) {
      root.document.body.dataset.locale = normalized;
    }
  }

  return {
    DEFAULT_LOCALE: DEFAULT_LOCALE,
    getLocale: getLocale,
    setLocale: setLocale,
    toggleLocale: toggleLocale,
    getDocumentLang: getDocumentLang,
    translateText: translateText,
    localizeValue: localizeValue,
    localizeDom: localizeDom,
    applyLocale: applyLocale,
  };
